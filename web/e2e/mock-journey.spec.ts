import { expect, test } from '@playwright/test'

test('sign-in and persistent item journey', async ({ page }, testInfo) => {
  const title = `Journey note ${testInfo.project.name}`
  await page.goto('/items')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.screenshot({ path: testInfo.outputPath('sign-in.png'), fullPage: true })
  await page.getByLabel('Email address').fill('one@example.test')
  await page.getByLabel('Password').fill('test-password-one')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Items' })).toBeVisible()
  await expect(page.getByText('Private item', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create item', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('editor.png'), fullPage: true })
  await page.getByRole('dialog').getByLabel('Title').fill(title)
  await page.getByRole('dialog').getByLabel('Description').fill('Created in an isolated browser session.')
  await page.getByRole('dialog').getByRole('button', { name: 'Create item' }).click()
  await expect(page.getByText(title, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Edit ${title}` }).click()
  await page.getByRole('dialog').getByLabel('Title').fill(`${title} updated`)
  await page.getByRole('dialog').getByRole('button', { name: 'Save changes' }).click()
  await page.reload()
  await expect(page.getByText(`${title} updated`, { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('items.png'), fullPage: true })
  await page.getByRole('button', { name: `Delete ${title} updated` }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete item' }).click()
  await expect(page.getByText(`${title} updated`, { exact: true })).toHaveCount(0)
  await page.context().clearCookies()
  await page.getByRole('button', { name: 'Create item', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Title').fill('Expired session')
  await page.getByRole('dialog').getByRole('button', { name: 'Create item' }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Email address').fill('one@example.test')
  await page.getByLabel('Password').fill('test-password-one')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Items' })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.reload()
  await expect(page).toHaveURL(/\/sign-in$/)
})
